/**
 * Runs after `dotnet publish`. Two jobs:
 *
 * 1. Fail the build if the publish did not land where angular.json expects it.
 *    `Microsoft.NET.Sdk.WebAssembly` writes static web assets under
 *    `<publish>/wwwroot/_framework`, not `<publish>/_framework`. Getting that path
 *    wrong produces an empty asset copy rather than an error, so the app builds fine
 *    and only breaks in the browser.
 *
 * 2. Record which SDK produced the runtime, so the app can show it. The file it
 *    writes is committed: a fresh clone has to compile before anyone has run a .NET
 *    build, and the pinned global.json keeps the value stable between machines.
 */
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, statSync, existsSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const FRAMEWORK_DIR = join('dotnet', 'artifacts', 'publish', 'wwwroot', '_framework');
const CSPROJ = join('dotnet', 'Toolbox.Wasm', 'Toolbox.Wasm.csproj');
const BUILD_PROPS = join('dotnet', 'Directory.Build.props');
const BUILD_INFO = join('src', 'environments', 'dotnet-build-info.ts');
const REQUIRED_ENTRY = 'dotnet.js';

// --- 1. verify -------------------------------------------------------------

if (!existsSync(FRAMEWORK_DIR)) {
  console.error(
    `\n[wasm] Expected published runtime at "${FRAMEWORK_DIR}" but the directory does not exist.` +
      `\n[wasm] Run "npm run build:wasm". If that succeeded, the SDK's publish layout has changed.\n`
  );
  process.exit(1);
}

const files = readdirSync(FRAMEWORK_DIR);

if (!files.includes(REQUIRED_ENTRY)) {
  console.error(
    `\n[wasm] "${REQUIRED_ENTRY}" is missing from "${FRAMEWORK_DIR}".` +
      `\n[wasm] The loader imports it by that exact name, so the tool would fail at runtime.\n`
  );
  process.exit(1);
}

// --- 2. record the build info ---------------------------------------------

/** The SDK that just built this, resolved through global.json like the publish was. */
const sdkVersion = execFileSync('dotnet', ['--version'], { encoding: 'utf8' }).trim();

/**
 * The TFM lives in Directory.Build.props so all three projects share one value, but a project
 * is still allowed to override it - so read them in MSBuild's precedence order.
 */
const readTargetFramework = (file) =>
  existsSync(file)
    ? /<TargetFramework>([^<]+)<\/TargetFramework>/.exec(readFileSync(file, 'utf8'))?.[1]
    : undefined;

const targetFramework =
  readTargetFramework(CSPROJ) ?? readTargetFramework(BUILD_PROPS) ?? 'unknown';

const contents = `/**
 * Generated by scripts/finalize-wasm-build.mjs during "npm run build:wasm".
 * Committed so a fresh clone compiles before anyone has run a .NET build.
 * Do not edit by hand.
 */
export const DOTNET_BUILD_INFO = {
  sdkVersion: '${sdkVersion}',
  targetFramework: '${targetFramework}',
} as const;
`;

const previous = existsSync(BUILD_INFO) ? readFileSync(BUILD_INFO, 'utf8') : null;
if (previous !== contents) {
  writeFileSync(BUILD_INFO, contents);
  console.log(`[wasm] build info updated: SDK ${sdkVersion}, ${targetFramework}`);
}

// Reported because payload size is the main ongoing risk of shipping a runtime.
const bytes = files.reduce((total, file) => {
  const stats = statSync(join(FRAMEWORK_DIR, file));
  return stats.isFile() && !file.endsWith('.br') && !file.endsWith('.gz')
    ? total + stats.size
    : total;
}, 0);

console.log(
  `[wasm] ${files.length} files in _framework, ${(bytes / 1024 / 1024).toFixed(1)} MB uncompressed.`
);
